#!/usr/bin/env python3
"""Builds src/command_names.rs: a readable name for every command group in
Onkyo's protocol spreadsheet, used where AVR Control has no label of its own
(e.g. the results of "Check on receiver").

Input is the same YAML gen_model_table.py reads:

    python tools/gen_command_names.py eiscp-commands-146.yaml > src/command_names.rs
"""
import re
import sys

import yaml


class Loader(yaml.SafeLoader):
    pass


Loader.add_constructor("tag:yaml.org,2002:seq", lambda l, n: tuple(l.construct_sequence(n)))


def clean(desc: str) -> str:
    # "Zone2 Balance Command" -> "Zone 2 balance",
    # "NET/USB List Title Info(for Network Control Only)" -> "NET/USB list title info"
    desc = re.sub(r"\s*\([^)]*\)", " ", desc)  # "(temporary)"
    desc = re.sub(r"\s*\(.*$", "", desc)  # an unclosed "(for ... only"
    desc = re.sub(r"\s+", " ", desc)
    desc = re.sub(r"\s*(Command|Operation Command)\s*$", "", desc).strip()
    desc = re.sub(r"\bZone(\d)", r"Zone \1", desc)
    words = desc.split()
    # Lower-case ordinary words, keep acronyms and the first word.
    out = [w if i == 0 or not w[:1].isupper() or w.isupper() or "/" in w else w.lower()
           for i, w in enumerate(words)]
    return " ".join(out)


def main() -> None:
    with open(sys.argv[1]) as f:
        data = yaml.load(f, Loader=Loader)
    names = {}
    for zone, commands in data.items():
        for group, info in (commands or {}).items():
            if len(group) == 3 and group not in names and info.get("description"):
                names[group] = clean(str(info["description"]))
    print("//! Generated by tools/gen_command_names.py from Onkyo's protocol")
    print("//! spreadsheet. Do not edit by hand.")
    print()
    print("/// (command group, readable name), sorted by group.")
    print("pub const COMMAND_NAMES: &[(&str, &str)] = &[")
    for group in sorted(names):
        name = names[group].replace("\\", "\\\\").replace('"', '\\"')
        print(f'    ("{group}", "{name}"),')
    print("];")


main()
